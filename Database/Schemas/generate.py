"""Build schema-organized SQL references from the canonical migrations and queries."""

import argparse
import re
from pathlib import Path

import sqlparse

DATABASE = Path(__file__).resolve().parents[1]
OUTPUT = DATABASE / "Schemas"
SCHEMAS = ("public", "core", "intake", "analytics", "performance", "statistic")
RELATION = r'((?:[a-z_]+\.)?(?:[a-z_][a-z_0-9]*|"[^"]+"))'
TABLE = re.compile(
    rf"^(?:CREATE TABLE (?:IF NOT EXISTS )?|ALTER TABLE |"
    rf"CREATE (?:UNIQUE )?INDEX (?:IF NOT EXISTS )?\S+\s+ON\s+){RELATION}", re.I
)
VIEW = re.compile(rf"^CREATE (?:OR REPLACE )?VIEW {RELATION}", re.I)
QUERY_RELATION = re.compile(rf"\b(?:INSERT\s+INTO|UPDATE|FROM)\s+{RELATION}", re.I)
SCHEMA = re.compile(r"^CREATE SCHEMA IF NOT EXISTS ([a-z_]+)", re.I)


def statements(path):
    for statement in sqlparse.split(path.read_text(encoding="utf-8")):
        sql = sqlparse.format(statement, strip_comments=True).strip()
        if sql:
            yield sql


def owner(relation):
    return relation.split(".", 1)[0] if "." in relation else "public"


def add(files, schema, kind, source, sql):
    if schema not in SCHEMAS:
        raise ValueError(f"Unrecognized schema {schema} in {source}")
    files.setdefault((schema, kind), []).append(f"-- Source: {source}\n{sql}")


def generate():
    files = {(schema, "tables"): [] for schema in SCHEMAS}
    files.update({(schema, "queries"): [] for schema in SCHEMAS})
    installer = (DATABASE / "Schema/install.psql").read_text(encoding="utf-8")
    for migration in re.findall(r"^\\ir\s+(\S+)", installer, re.M):
        path = DATABASE / "Schema" / migration
        source = path.relative_to(DATABASE)
        for sql in statements(path):
            if match := SCHEMA.match(sql):
                add(files, match[1], "tables", source, sql)
            elif match := TABLE.match(sql):
                add(files, owner(match[1]), "tables", source, sql)
            elif match := VIEW.match(sql):
                add(files, owner(match[1]), "views", source, sql)
            elif re.match(r"^(CREATE|ALTER)\s+(TABLE|VIEW|SCHEMA|INDEX|UNIQUE INDEX)\b", sql, re.I):
                raise ValueError(f"Cannot classify definition in {source}: {sql[:100]}")
    for name in ("intake", "promote", "read", "explore"):
        path = DATABASE / "Queries" / f"{name}.sql"
        source = path.relative_to(DATABASE)
        for sql in statements(path):
            match = QUERY_RELATION.search(sql)
            if not sql.upper().startswith("PREPARE ") or not match:
                raise ValueError(f"Cannot classify query in {source}: {sql[:100]}")
            schema = "public" if match[1].startswith("information_schema.") else owner(match[1])
            add(files, schema, "queries", source, sql)
    # Prepared reads for the newer display and scorecard views.
    for schema, path in (
        ("performance", OUTPUT / "performance" / "read.sql"),
        ("statistic", OUTPUT / "statistic" / "read.sql"),
    ):
        for sql in statements(path):
            add(files, schema, "queries", path.relative_to(DATABASE), sql)
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if references need regeneration.")
    args = parser.parse_args()
    stale = []
    files = generate()
    for (schema, kind), blocks in files.items():
        path = OUTPUT / schema / f"{kind}.sql"
        banner = (
            "-- Generated by Database/Schemas/generate.py. Edit the source SQL instead.\n"
            "-- Schema-organized reference. Use Database/Schema/install.psql to install database objects.\n"
        )
        if kind == "queries":
            banner += "-- PREPARE statements are scoped to the current database session.\n"
        body = "\n\n".join(blocks) if blocks else "-- This schema exposes views and has no base tables."
        expected = f"{banner}\n{body}\n"
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != expected:
                stale.append(str(path.relative_to(DATABASE)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8")
    expected_paths = {OUTPUT / schema / f"{kind}.sql" for schema, kind in files}
    for path in OUTPUT.glob("*/views.sql"):
        if path not in expected_paths:
            stale.append(str(path.relative_to(DATABASE)))
    if stale:
        parser.exit(1, "Stale schema references: " + ", ".join(stale) + "\n")


if __name__ == "__main__":
    main()
